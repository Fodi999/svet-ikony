// scripts/calendar-geo/generate-production-seed.mjs
//
// Generates an idempotent, auditable SQL seed for the base calendar_geo_*
// data (sources, rules, the 4 movable-feast entities/translations, days,
// occurrences) for a given year, mirroring the exact data and SQL shapes
// produced by scripts/calendar-geo/import-local.mjs.
//
// This script is intentionally NOT a database client:
//  - it holds no Cloudflare credentials of any kind,
//  - it never opens a database connection (local or remote),
//  - it only reads local source files and writes a plain .sql text file.
//
// scripts/calendar-geo/import-local.mjs is read-only reference logic here
// and is never imported, executed, or modified by this script.
//
// Usage:
//   node scripts/calendar-geo/generate-production-seed.mjs [--year=YYYY] [--out=PATH]
//
// Output: an idempotent SQL file (INSERT ... ON CONFLICT DO NOTHING only)
// suitable for `wrangler d1 execute <db> --remote --file=<PATH>`, which the
// operator must run themselves after reviewing the audit report below.

import {readFileSync, writeFileSync} from 'node:fs';
import {resolve, dirname, join} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {registerHooks} from 'node:module';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

// Same '@/' resolution shim as import-local.mjs, so geo-resolver.ts's own
// internal '@/...' imports (e.g. '@/lib/telegram/julian-calendar') resolve
// correctly. This process never touches node:sqlite or any DB driver.
registerHooks({resolve(specifier, context, next) {
  return next(specifier.startsWith('@/') ? pathToFileURL(join(root, `${specifier.slice(2)}.ts`)).href : specifier, context);
}});

const args = process.argv.slice(2);
for (const arg of args) {
  if (arg !== '--apply' && !/^--year=\d{4}$/.test(arg) && !/^--out=.+$/.test(arg)) {
    throw new Error(`Unrecognized argument: ${arg}. Only --year=YYYY and --out=PATH are accepted.`);
  }
  if (arg === '--apply') {
    throw new Error('This script never applies anything itself; --apply is not a valid option here.');
  }
}

const year = Number(args.find(arg => arg.startsWith('--year='))?.slice(7) ?? 2026);
const outPath = args.find(arg => arg.startsWith('--out='))?.slice(6) ?? `/tmp/calendar-geo-production-${year}.sql`;

// Reuse the exact same authoritative date-math module import-local.mjs uses.
// Reading it (not modifying, not running it) avoids re-implementing Julian
// Pascha computus and risking a subtly different result from production.
const {civilDays, resolveCalendarDay} = await import(pathToFileURL(join(root, 'lib/church/geo-resolver.ts')).href);

const dates = civilDays(year);
const sourceBytes = readFileSync(join(root, 'lib/church/data/orthodox-fixed-calendar.json'));
const snapshot = JSON.parse(sourceBytes);
if (snapshot.calendar !== 'fixed-julian-month-day' || Object.keys(snapshot.days).length !== 366) {
  throw new Error('Unexpected source snapshot');
}
const hash = createHash('sha256').update(sourceBytes).update('calendar-geo-v1').digest('hex');
const policy = {calendarSystem: 'julian', tradition: 'orthodox', jurisdiction: ''};

const rules = [];
for (const [monthDay, day] of Object.entries(snapshot.days)) {
  const [month, date] = monthDay.split('-').map(Number);
  for (const entry of day.entries) {
    rules.push({
      ...policy, id: `oca-fixed:${monthDay}:${entry.id}`, type: 'fixed', month, day: date,
      title: entry.title, sourceId: `oca-fixed:${monthDay}`, sourceUrl: day.sourceUrls[0],
    });
  }
}

const movable = [
  {id: 'pascha', offset: 0, names: {en: 'Pascha', uk: 'Пасха', ru: 'Пасха'}},
  {id: 'palm-sunday', offset: -7, names: {en: 'Palm Sunday', uk: 'Вхід Господній у Єрусалим', ru: 'Вход Господень в Иерусалим'}},
  {id: 'ascension', offset: 39, names: {en: 'Ascension', uk: 'Вознесіння Господнє', ru: 'Вознесение Господне'}},
  {id: 'pentecost', offset: 49, names: {en: 'Pentecost', uk: 'П’ятидесятниця', ru: 'Пятидесятница'}},
];
for (const entry of movable) {
  rules.push({...policy, id: `paschal:${entry.id}`, type: 'movable', anchor: 'orthodox_pascha', offsetDays: entry.offset, title: entry.names.en, sourceId: 'oca-paschal-cycle'});
}

const resolved = dates.map(date => ({date, ids: resolveCalendarDay(date, rules, policy)}));

// ---- SQL emission (no DB access; text only) ----

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}
function sqlNumber(value) {
  if (value === null || value === undefined) return 'NULL';
  return String(value);
}

const lines = [];
lines.push('-- Generated by scripts/calendar-geo/generate-production-seed.mjs');
lines.push(`-- year=${year} sourceHash=${hash}`);
lines.push(`-- generatedAt=${new Date().toISOString()}`);
lines.push('-- All statements are INSERT ... ON CONFLICT DO NOTHING (idempotent, safe to re-run).');
lines.push('-- No CREATE/ALTER/UPDATE/DELETE/DROP statements are present in this file.');
lines.push('');

let sourceCount = 0;
lines.push('-- calendar_geo_sources: fixed-calendar day sources + the paschal-cycle source');
for (const [monthDay, day] of Object.entries(snapshot.days)) {
  lines.push(`INSERT INTO calendar_geo_sources(id,source_type,source_url,external_id,retrieved_at) VALUES (${sqlString(`oca-fixed:${monthDay}`)},'church_source',${sqlString(day.sourceUrls[0])},${sqlString(monthDay)},${sqlString(snapshot.retrievedAt)}) ON CONFLICT(id) DO NOTHING;`);
  sourceCount++;
}
lines.push(`INSERT INTO calendar_geo_sources(id,source_type,source_url,external_id,retrieved_at) VALUES ('oca-paschal-cycle','church_source','https://www.oca.org/fs/paschal-cycle','paschal-cycle','2026-09-19') ON CONFLICT(id) DO NOTHING;`);
sourceCount++;
lines.push('');

let entityCount = 0;
let translationCount = 0;
lines.push('-- calendar_geo_entities + calendar_geo_translations: the 4 movable feasts only');
for (const entry of movable) {
  const id = `feast:${entry.id}`;
  lines.push(`INSERT INTO calendar_geo_entities(id,entity_type,canonical_name) VALUES (${sqlString(id)},'feast',${sqlString(entry.names.en)}) ON CONFLICT(id) DO NOTHING;`);
  entityCount++;
  for (const [locale, name] of Object.entries(entry.names)) {
    const translationId = `${id}:${locale}`;
    const translationStatus = locale === 'en' ? 'source' : 'needs_review';
    lines.push(`INSERT INTO calendar_geo_translations(id,entity_id,locale,name,translation_status,source_locale,source_id) VALUES (${sqlString(translationId)},${sqlString(id)},${sqlString(locale)},${sqlString(name)},${sqlString(translationStatus)},${sqlString(locale)},'oca-paschal-cycle') ON CONFLICT(id) DO NOTHING;`);
    translationCount++;
  }
}
lines.push('');

let ruleCount = 0;
lines.push('-- calendar_geo_rules: fixed-calendar rules (entity_id NULL, no fabricated matches) + movable-feast rules');
for (const rule of rules) {
  const entityId = rule.type === 'movable' ? `feast:${rule.id.slice(8)}` : null;
  const verificationStatus = rule.type === 'movable' ? 'verified' : 'needs_review';
  lines.push(`INSERT INTO calendar_geo_rules(id,entity_id,source_title,source_id,rule_type,month,day,anchor,offset_days,calendar_system,tradition,verification_status) VALUES (${sqlString(rule.id)},${sqlString(entityId)},${sqlString(rule.title)},${sqlString(rule.sourceId)},${sqlString(rule.type)},${sqlNumber(rule.month ?? null)},${sqlNumber(rule.day ?? null)},${sqlString(rule.anchor ?? null)},${sqlNumber(rule.offsetDays ?? null)},'julian','orthodox',${sqlString(verificationStatus)}) ON CONFLICT(id) DO NOTHING;`);
  ruleCount++;
}
lines.push('');

let dayCount = 0;
lines.push(`-- calendar_geo_days: civil days for ${year}`);
const now = new Date().toISOString();
for (const day of resolved) {
  lines.push(`INSERT INTO calendar_geo_days(civil_date,calendar_system,tradition,jurisdiction,resolved_at) VALUES (${sqlString(day.date)},'julian','orthodox','',${sqlString(now)}) ON CONFLICT DO NOTHING;`);
  dayCount++;
}
lines.push('');

let occurrenceCount = 0;
lines.push(`-- calendar_geo_occurrences: rule occurrences for ${year}`);
for (const day of resolved) {
  for (const id of day.ids) {
    lines.push(`INSERT INTO calendar_geo_occurrences(rule_id,civil_date,calendar_system,tradition,jurisdiction) VALUES (${sqlString(id)},${sqlString(day.date)},'julian','orthodox','') ON CONFLICT DO NOTHING;`);
    occurrenceCount++;
  }
}
lines.push('');

const sql = lines.join('\n');
writeFileSync(outPath, sql, 'utf8');
const sqlBytes = readFileSync(outPath);
const sqlHash = createHash('sha256').update(sqlBytes).digest('hex');

// Statement-type audit: confirm only INSERT statements are present.
const statementLines = sql.split('\n').filter(line => /^\s*(INSERT|UPDATE|DELETE|DROP|ALTER|CREATE)\b/i.test(line));
const statementTypes = new Set(statementLines.map(line => line.trim().split(/\s+/)[0].toUpperCase()));

console.log(JSON.stringify({
  outPath,
  year,
  sourceSnapshotHash: hash,
  sqlFileBytes: sqlBytes.length,
  sqlFileSha256: sqlHash,
  counts: {
    sources: sourceCount,
    rules: ruleCount,
    days: dayCount,
    occurrences: occurrenceCount,
    entities: entityCount,
    translations: translationCount,
  },
  statementTypesPresent: [...statementTypes],
  statementCount: statementLines.length,
}, null, 2));
