#!/usr/bin/env node
/**
 * Generates an idempotent, additive-only SQL seed file for the 30-day
 * Julian-calendar content population task (civil 2026-09-01..2026-09-30 /
 * old-style 2026-08-19..2026-09-17). Safe to run this generator (and the
 * resulting SQL) more than once: every INSERT is guarded by
 * `WHERE NOT EXISTS (...)` keyed on the same lookup the app itself uses
 * (church_calendar_days.date_old_style, then calendar_day_id + language
 * [+ prayer_type] for the per-type tables) -- a second run touches zero
 * rows. No DELETE/DROP/UPDATE anywhere in this file's output.
 *
 * Usage: node scripts/calendar-seed/generate-sql.mjs > scripts/calendar-seed/seed.sql
 * Then:  wrangler d1 execute svetikony-production --remote --file=scripts/calendar-seed/seed.sql
 */
import { randomUUID } from 'node:crypto';
import { DAYS } from './data.mjs';

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

