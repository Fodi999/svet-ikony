const lines = [];
function emit(sql) {
  lines.push(sql.trim() + ';');
}

lines.push('-- Auto-generated by scripts/calendar-seed/generate-sql.mjs -- DO NOT hand-edit.');
lines.push('-- Idempotent additive seed: civil 2026-09-01..2026-09-30 / old-style 2026-08-19..2026-09-17.');
lines.push('');

for (const [index, day] of DAYS.entries()) {
  lines.push(`-- ==== ${day.civilDate} (old-style ${day.oldStyle}) ====`);

  if (!day.existingCalendarDayId) {
    const calendarId = randomUUID();
    emit(`
      INSERT INTO church_calendar_days
        (id, date_old_style, date_new_style, calendar_type, title, slug, language, day_type, description, status)
      SELECT ${sqlString(calendarId)}, ${sqlString(day.oldStyle)}, ${sqlString(day.civilDate)}, 'both',
        ${sqlString(day.calendarTitle)}, ${sqlString(`${day.oldStyle}-${calendarId.slice(0, 8)}`)}, 'uk',
        ${sqlString(day.dayType)}, ${sqlString(day.calendarDescription)}, 'published'
      WHERE NOT EXISTS (SELECT 1 FROM church_calendar_days WHERE date_old_style = ${sqlString(day.oldStyle)})
    `);
  }

  const calendarDaySubquery = `(SELECT id FROM church_calendar_days WHERE date_old_style = ${sqlString(day.oldStyle)})`;

  if (day.saint) {
    const saintId = randomUUID();
    emit(`
      INSERT INTO church_saints
        (id, calendar_day_id, slug, name, short_description, biography, language, status)
      SELECT ${sqlString(saintId)}, ${calendarDaySubquery}, ${sqlString(`${day.oldStyle}-${saintId.slice(0, 8)}`)},
        ${sqlString(day.saint.name)}, ${sqlString(day.saint.shortDescription)}, ${sqlString(day.saint.biography)}, 'uk', 'published'
      WHERE NOT EXISTS (
        SELECT 1 FROM church_saints WHERE calendar_day_id = ${calendarDaySubquery} AND language = 'uk'
      )
    `);
  }

  if (day.gospel) {
    const gospelId = randomUUID();
    emit(`
      INSERT INTO church_gospel_readings
        (id, calendar_day_id, slug, title, reference, text, explanation, language, status)
      SELECT ${sqlString(gospelId)}, ${calendarDaySubquery}, ${sqlString(`${day.oldStyle}-${gospelId.slice(0, 8)}`)},
        ${sqlString(day.gospel.title)}, ${sqlString(day.gospel.reference)}, '', ${sqlString(day.gospel.explanation)}, 'uk', 'published'
      WHERE NOT EXISTS (
        SELECT 1 FROM church_gospel_readings WHERE calendar_day_id = ${calendarDaySubquery} AND language = 'uk'
      )
    `);
  }

  if (day.faithStory) {
    const articleId = randomUUID();
    emit(`
      INSERT INTO church_articles
        (id, calendar_day_id, title, slug, content, language, status)
      SELECT ${sqlString(articleId)}, ${calendarDaySubquery}, ${sqlString(day.faithStory.title)},
        ${sqlString(`${day.oldStyle}-${articleId.slice(0, 8)}`)}, ${sqlString(day.faithStory.content)}, 'uk', 'published'
      WHERE NOT EXISTS (
        SELECT 1 FROM church_articles WHERE calendar_day_id = ${calendarDaySubquery} AND language = 'uk'
      )
    `);
  }

  const morning = MORNING_PRAYERS[index % MORNING_PRAYERS.length];
  const morningId = randomUUID();
  emit(`
    INSERT INTO church_prayers
      (id, calendar_day_id, slug, title, text, source, source_url, language, prayer_type, status)
    SELECT ${sqlString(morningId)}, ${calendarDaySubquery}, ${sqlString(`${day.oldStyle}-morning-${morningId.slice(0, 8)}`)},
      ${sqlString(morning.title)}, ${sqlString(morning.text)}, ${sqlString(morning.source)}, ${sqlString(morning.sourceUrl)},
      'uk', 'morning', 'published'
    WHERE NOT EXISTS (
      SELECT 1 FROM church_prayers WHERE calendar_day_id = ${calendarDaySubquery} AND language = 'uk' AND prayer_type = 'morning'
    )
  `);

  const evening = EVENING_PRAYERS[index % EVENING_PRAYERS.length];
  const eveningId = randomUUID();
  emit(`
    INSERT INTO church_prayers
      (id, calendar_day_id, slug, title, text, source, source_url, language, prayer_type, status)
    SELECT ${sqlString(eveningId)}, ${calendarDaySubquery}, ${sqlString(`${day.oldStyle}-evening-${eveningId.slice(0, 8)}`)},
      ${sqlString(evening.title)}, ${sqlString(evening.text)}, ${sqlString(evening.source)}, ${sqlString(evening.sourceUrl)},
      'uk', 'evening', 'published'
    WHERE NOT EXISTS (
      SELECT 1 FROM church_prayers WHERE calendar_day_id = ${calendarDaySubquery} AND language = 'uk' AND prayer_type = 'evening'
    )
  `);

  lines.push('');
}

process.stdout.write(lines.join('\n') + '\n');
